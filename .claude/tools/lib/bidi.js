/* PHONE GAT — בידוד ריצות לטיניות בתוך טקסט עברי.
 *
 * ============================================================================
 * הבאג שהמודול הזה נולד ממנו, והוא היה גלוי לכל מבקר ב-20 עמודים.
 * ============================================================================
 *
 * תא בטבלת מפרט מכיל עברית ולטינית יחד. אלגוריתם ה-bidi מסדר מחדש את הרצף, ויחידה לטינית
 * שצמודה למספר (MP, GHz, x) היא תו L חזק, ולכן לפי כלל W7 המספר שאחריה נהפך ל-L בזמן
 * שהראשון נשאר EN. התוצאה נמדדה בדפדפן, על סדר הפיקסלים ולא על ה-DOM:
 *
 *   במקור:  שלוש עדשות אחוריות: 50MP, 12MP ו-5MP
 *   על המסך: שלוש עדשות אחוריות: 12MP 50MP, ו-5MP     ← הראשית נראית 12MP
 *
 *   במקור:  162.2 x 77.5 x 7.4 מ״מ
 *   על המסך: 162.2 7.4 x 77.5 x מ״מ
 *
 *   במקור:  8 ליבות, 2.9GHz, 2.6GHz ו-1.9GHz
 *   על המסך: 8 ליבות, 2.6GHz 2.9GHz, ו-1.9GHz         ← הליבה המהירה נראית 2.6
 *
 * עמוד שמזמין להשוות ואי אפשר לסמוך על המספרים שבו מאבד בדיוק את מה שהוא בא לתת.
 *
 * ההערה שכבר הייתה בקוד חזתה את זה במילים "ומידה הופכת סדר ספרות", אבל העוטף הוחל על שם
 * הדגם בלבד ולא על ערכי המפרט. אי אפשר לעטוף ערך שלם כי יש בו עברית, ולכן כאן עוטפים כל
 * ריצה שיש בה אות לטינית.
 *
 * למה מודול נפרד: שלושה מחוללים מרנדרים תאי מפרט, וזה בדיוק סוג הפונקציה שאם תיכתב פעמיים
 * תתפצל. אותו שיקול שהוליד את traits.js.
 */
'use strict';

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/* ריצה = תווים לטיניים, ספרות וסימני פיסוק צמודים, שאפשר שיהיו מופרדים ברווחים בודדים.
 * המחלקה לא מכילה אותיות עבריות, ולכן ריצה נעצרת מעצמה בגבול העברי, ו"ו-5MP" לא נגרר
 * לתוך הריצה שלפניו.
 *
 * הריצה מורחבת גם על רווחים כדי ש-"Wi-Fi 6" ו-"162.2 x 77.5 x 7.4" יבודדו כיחידה אחת.
 * ריצה בלי אף אות לטינית (למשל "9:00" או "5,000,000") אינה נעטפת, כי היא מסודרת נכון
 * מלכתחילה ועטיפה מיותרת רק מוסיפה תגיות. */
/* סוגריים אינם במחלקה בכוונה. בגרסה הראשונה הם היו, ו-"4K (3840x2160)" יצא
 * "<bdo>4K</bdo> (<bdo>3840x2160)</bdo>" — הסוגר הנסגר נבלע לתוך הריצה בלי פותח מקביל.
 * הסוגריים הם חלק מהמשפט העברי שעוטף, ולכן הם נשארים בחוץ. */
var RUN = /[A-Za-z0-9][A-Za-z0-9.,:%\/+–\-]*(?:[ ]+[A-Za-z0-9][A-Za-z0-9.,:%\/+–\-]*)*/g;

/* ההברחה נעשית על מקטעים ולא על המחרוזת כולה, ואז התגיות מוזרקות גולמיות.
 * הסדר הזה חשוב: אילו היינו מבריחים קודם, "&amp;" היה הופך ל-"&amp;amp;" והאותיות a,m,p
 * היו נראות לרגקס כריצה לטינית שצריך לעטוף, מה שהיה שובר את הישות. */
function ltrRuns(raw) {
  if (raw === null || raw === undefined) return '';
  var s = String(raw), out = '', last = 0, m;
  RUN.lastIndex = 0;
  while ((m = RUN.exec(s)) !== null) {
    var run = m[0];
    /* פיסוק בסוף הריצה הוא של המשפט העברי ולא של הריצה, ולכן הוא נשאר בחוץ */
    var core = run.replace(/[.,:\s]+$/, '');
    var tail = run.slice(core.length);
    out += esc(s.slice(last, m.index));
    if (/[A-Za-z]/.test(core)) out += '<bdo dir="ltr">' + esc(core) + '</bdo>' + esc(tail);
    else out += esc(run);
    last = m.index + run.length;
  }
  return out + esc(s.slice(last));
}

module.exports = { esc: esc, ltrRuns: ltrRuns };
